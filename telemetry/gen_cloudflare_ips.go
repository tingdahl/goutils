//go:build ignore

package main

import (
	"bytes"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"strings"
	"time"
)

const (
	ipv4URL = "https://www.cloudflare.com/ips-v4"
	ipv6URL = "https://www.cloudflare.com/ips-v6"
)

func fetchLines(url string) ([]string, error) {
	client := &http.Client{Timeout: 15 * time.Second}
	resp, err := client.Get(url)
	if err != nil {
		return nil, fmt.Errorf("HTTP GET %s failed: %w", url, err)
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("HTTP GET %s returned status %d", url, resp.StatusCode)
	}

	body, err := io.ReadAll(resp.Body)
	if err != nil {
		return nil, fmt.Errorf("reading body from %s failed: %w", url, err)
	}

	var lines []string
	for _, line := range strings.Split(string(body), "\n") {
		trimmed := strings.TrimSpace(line)
		if trimmed != "" && !strings.HasPrefix(trimmed, "#") {
			lines = append(lines, trimmed)
		}
	}
	return lines, nil
}

func main() {
	ipv4s, err := fetchLines(ipv4URL)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error fetching IPv4 ranges: %v\n", err)
		os.Exit(1)
	}

	ipv6s, err := fetchLines(ipv6URL)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error fetching IPv6 ranges: %v\n", err)
		os.Exit(1)
	}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by gen_cloudflare_ips.go; DO NOT EDIT.\n")
	buf.WriteString("// Source: https://www.cloudflare.com/ips-v4 and https://www.cloudflare.com/ips-v6\n\n")
	buf.WriteString("package telemetry\n\n")
	buf.WriteString("import (\n")
	buf.WriteString("	\"net\"\n")
	buf.WriteString("	\"sync\"\n")
	buf.WriteString(")\n\n")

	buf.WriteString("var (\n")
	buf.WriteString("	cloudflareCIDRStrings = []string{\n")
	buf.WriteString("		// IPv4\n")
	for _, ip := range ipv4s {
		buf.WriteString(fmt.Sprintf("		%q,\n", ip))
	}
	buf.WriteString("		// IPv6\n")
	for _, ip := range ipv6s {
		buf.WriteString(fmt.Sprintf("		%q,\n", ip))
	}
	buf.WriteString("	}\n")
	buf.WriteString("	cloudflareCIDRs []*net.IPNet\n")
	buf.WriteString("	initCFOnce      sync.Once\n")
	buf.WriteString(")\n\n")

	buf.WriteString("func initCloudflareCIDRs() {\n")
	buf.WriteString("	for _, cidr := range cloudflareCIDRStrings {\n")
	buf.WriteString("		_, netCIDR, err := net.ParseCIDR(cidr)\n")
	buf.WriteString("		if err == nil {\n")
	buf.WriteString("			cloudflareCIDRs = append(cloudflareCIDRs, netCIDR)\n")
	buf.WriteString("		}\n")
	buf.WriteString("	}\n")
	buf.WriteString("}\n\n")

	buf.WriteString("// IsCloudflareIP checks if the given IP address is in Cloudflare\x27s published edge proxy CIDRs.\n")
	buf.WriteString("func IsCloudflareIP(ip net.IP) bool {\n")
	buf.WriteString("	if ip == nil {\n")
	buf.WriteString("		return false\n")
	buf.WriteString("	}\n")
	buf.WriteString("	initCFOnce.Do(initCloudflareCIDRs)\n")
	buf.WriteString("	for _, cidr := range cloudflareCIDRs {\n")
	buf.WriteString("		if cidr.Contains(ip) {\n")
	buf.WriteString("			return true\n")
	buf.WriteString("		}\n")
	buf.WriteString("	}\n")
	buf.WriteString("	return false\n")
	buf.WriteString("}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error formatting generated Go code: %v\n", err)
		os.Exit(1)
	}

	targetPath := filepath.Join("telemetry", "cloudflare_ips.go")
	if _, err := os.Stat("telemetry"); os.IsNotExist(err) {
		targetPath = "cloudflare_ips.go"
	}

	if err := os.WriteFile(targetPath, formatted, 0644); err != nil {
		fmt.Fprintf(os.Stderr, "Error writing %s: %v\n", targetPath, err)
		os.Exit(1)
	}

	fmt.Printf("Successfully generated %s (%d IPv4, %d IPv6 prefixes)\n", targetPath, len(ipv4s), len(ipv6s))
}
